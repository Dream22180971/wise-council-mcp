// 合并白天桌（标记 desk: day）+ 夜晚桌/东方席位/共用席
import { nightAdvisors } from "./night.js";

export const advisors: Advisor[] = [
  ...dayAdvisors.map((a) => ({ ...a, desk: "day" as const })),
  ...nightAdvisors,
];

export function getAdvisorById(id: string): Advisor | undefined {
  return advisors.find((a) => a.id === id);
}

export function getAdvisorsByRole(role: string): Advisor[] {
  return advisors.filter((a) => a.role === role);
}

export function getAdvisorsByDesk(desk: "day" | "night"): Advisor[] {
  return advisors.filter((a) => a.desk === desk || a.desk === "both");
}

export function listAdvisorIds(): string[] {
  return advisors.map((a) => a.id);
}
